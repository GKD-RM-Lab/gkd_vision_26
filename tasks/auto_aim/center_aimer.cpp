#include "center_aimer.hpp"

#include <yaml-cpp/yaml.h>

#include <algorithm>
#include <chrono>
#include <cmath>
#include <cstdint>

#include "tools/math_tools.hpp"
#include "tools/trajectory.hpp"

namespace auto_aim
{

CenterAimer::CenterAimer(const std::string & config_path)
{
  const auto yaml = YAML::LoadFile(config_path);
  yaw_offset_ = yaml["yaw_offset"].as<double>() / 57.3;
  high_speed_delay_time_ = yaml["high_speed_delay_time"].as<double>();
  low_speed_delay_time_ = yaml["low_speed_delay_time"].as<double>();
  decision_speed_ = yaml["decision_speed"].as<double>();
}

void CenterAimer::reset_tracking() { last_pitch_.reset(); }

io::Command CenterAimer::aim(
  const std::list<Target> & targets, std::chrono::steady_clock::time_point timestamp,
  const io::Command & armor_command, double bullet_speed)
{
  if (targets.empty()) return {false, false, 0, 0};

  // Pitch is still generated by the original Aimer. When it cannot select an armor during
  // spinning, keep the last valid pitch so center-yaw tracking remains continuous.
  if (armor_command.control) last_pitch_ = armor_command.pitch;
  if (!last_pitch_.has_value()) return {false, false, 0, 0};

  auto target = targets.front();
  const auto state = target.ekf_x();
  double flight_time = 0.0;
  if (bullet_speed > 0) {
    const tools::Trajectory trajectory(
      bullet_speed, std::hypot(state[0], state[2]), state[4]);
    if (!trajectory.unsolvable) flight_time = trajectory.fly_time;
  }

  const auto predict_time =
    std::max(std::chrono::steady_clock::now(), timestamp) +
    std::chrono::microseconds(
      static_cast<int64_t>((processing_delay(target) + flight_time) * 1e6));
  target.predict(predict_time);

  const auto predicted_state = target.ekf_x();
  const auto center_yaw = std::atan2(predicted_state[2], predicted_state[0]);
  return {true, false, tools::limit_rad(center_yaw + yaw_offset_), *last_pitch_};
}

double CenterAimer::processing_delay(const Target & target) const
{
  return std::abs(target.ekf_x()[7]) > decision_speed_ ? high_speed_delay_time_
                                                       : low_speed_delay_time_;
}

}  // namespace auto_aim
